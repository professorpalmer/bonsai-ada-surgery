def ref_trits(b: int) -> list[int]:
    v = b
    out = []
    for _ in range(5):
        w = v * 3
        out.append((w >> 8) - 1)
        v = w & 0xFF
    return out


def lut_trits(b: int) -> list[int]:
    packed = LUT[b]
    return [((packed >> (2 * n)) & 3) - 1 for n in range(5)]


def main() -> None:
    bad = 0
    for b in range(256):
        if ref_trits(b) != lut_trits(b):
            bad += 1
            if bad <= 8:
                print(f"mismatch b={b} ref={ref_trits(b)} lut={lut_trits(b)}")
    print(f"checked=256 mismatches={bad}")
    raise SystemExit(1 if bad else 0)


if __name__ == "__main__":
    main()
